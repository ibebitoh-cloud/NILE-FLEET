const uiPhraseTranslations: Record<string, string> = (() => {
  const result: Record<string, string> = { ...entityTranslations, ...uiExtraTranslations };
  const en = translations.en as Record<string, string>;
  const ar = translations.ar as Record<string, string>;
  Object.keys(en).forEach(key => {
    if (en[key] && ar[key] && en[key] !== ar[key]) result[en[key]] = ar[key];
  });
  Object.entries(dynamicTranslations).forEach(([key, value]) => { result[key] = value; });
  return result;
})();

export const translateUiText = (value: string, lang: 'en' | 'ar'): string => {
  if (lang === 'en' || !value) return value;
  const cached = uiPhraseTextCache.get(value);
  if (cached !== undefined) return cached;
  const exact = uiPhraseTranslations[value.toUpperCase()];
  if (exact) return exact;
  let translated = value;
  const phrases = Object.keys(uiPhraseTranslations).sort((a, b) => b.length - a.length);
  for (const phrase of phrases) {
    const replacement = uiPhraseTranslations[phrase];
    if (!phrase || !replacement || phrase === replacement) continue;
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const startsWithWord = /^[\p{L}\p{N}]/u.test(phrase);
    const endsWithWord = /[\p{L}\p{N}]$/u.test(phrase);
    const pattern = `${startsWithWord ? '(?<![\\p{L}\\p{N}])' : ''}${escaped}${endsWithWord ? '(?![\\p{L}\\p{N}])' : ''}`;
    translated = translated.replace(new RegExp(pattern, 'giu'), replacement);
  }
  if (uiPhraseTextCache.size > 5000) uiPhraseTextCache.clear();
  uiPhraseTextCache.set(value, translated);
  return translated;
};
