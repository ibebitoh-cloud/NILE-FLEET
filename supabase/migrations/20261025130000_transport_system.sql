-- Transport operations system: customer price lists (trucking / container
-- transport rates) and its own user roster, kept apart from the Genset app.
--
-- Access model
--   * transport_users maps a Supabase Auth user to a Transport role
--     (ADMIN = full edit, VIEWER = read only).
--   * Genset ADMIN / MANAGER profiles are treated as Transport ADMIN so the
--     company administrators do not need a second account.
--   * Prices are only readable by signed-in users who hold a Transport role.

create table if not exists public.transport_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('ADMIN', 'VIEWER')),
  name text,
  email text,
  created_at timestamptz not null default now()
);

alter table public.transport_users enable row level security;

create or replace function private.transport_role()
returns text
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select coalesce(
    (select case when p.role in ('ADMIN'::public.user_role, 'MANAGER'::public.user_role) then 'ADMIN' end
       from public.profiles p
      where p.id = (select auth.uid()) and coalesce(p.revoked, false) = false),
    (select tu.role from public.transport_users tu where tu.user_id = (select auth.uid()))
  );
$$;

revoke all on function private.transport_role() from public, anon;
grant execute on function private.transport_role() to authenticated;

drop policy if exists "transport users read own or admin" on public.transport_users;
create policy "transport users read own or admin"
on public.transport_users for select to authenticated
using (user_id = (select auth.uid()) or private.transport_role() = 'ADMIN');

create table if not exists public.transport_rates (
  id bigint generated by default as identity primary key,
  customer text not null,
  load_port text not null default '',
  destination text not null default '',
  transit_port text not null default '',
  price_1x20 numeric(12,2) not null default 0,
  price_2x20 numeric(12,2) not null default 0,
  price_40dc numeric(12,2) not null default 0,
  price_40rf numeric(12,2) not null default 0,
  currency text not null default 'EGP',
  notes text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create index if not exists transport_rates_customer_idx on public.transport_rates (customer);
create index if not exists transport_rates_destination_idx on public.transport_rates (destination);

alter table public.transport_rates enable row level security;

drop policy if exists "transport rates read" on public.transport_rates;
create policy "transport rates read"
on public.transport_rates for select to authenticated
using (private.transport_role() is not null);

drop policy if exists "transport rates admin insert" on public.transport_rates;
create policy "transport rates admin insert"
on public.transport_rates for insert to authenticated
with check (private.transport_role() = 'ADMIN');

drop policy if exists "transport rates admin update" on public.transport_rates;
create policy "transport rates admin update"
on public.transport_rates for update to authenticated
using (private.transport_role() = 'ADMIN')
with check (private.transport_role() = 'ADMIN');

drop policy if exists "transport rates admin delete" on public.transport_rates;
create policy "transport rates admin delete"
on public.transport_rates for delete to authenticated
using (private.transport_role() = 'ADMIN');

create or replace function public.transport_rates_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  new.updated_by := (select auth.uid());
  return new;
end;
$$;

drop trigger if exists transport_rates_touch on public.transport_rates;
create trigger transport_rates_touch
before insert or update on public.transport_rates
for each row execute function public.transport_rates_touch();

-- Lets the app ask "what can I do here?" without reading other tables.
create or replace function public.my_transport_role()
returns text
language sql
stable
security invoker
set search_path = ''
as $$ select private.transport_role(); $$;

revoke all on function public.my_transport_role() from public, anon;
grant execute on function public.my_transport_role() to authenticated;
