// Generates invoice-maker/theme-reset.css: pins the Tailwind colors used by the
// Invoice Maker so the app-wide Day/Night theme overrides in index.html don't repaint it.
const fs = require('fs'), path = require('path');
const root = process.argv[2] || path.join(__dirname, '..');
const colors = require(path.join(root, 'node_modules/tailwindcss/colors.js'));
const files = [];
const walk = d => fs.readdirSync(d, { withFileTypes: true }).forEach(e => { const p = path.join(d, e.name); e.isDirectory() ? walk(p) : /\.tsx?$/.test(p) && files.push(p); });
walk(path.join(root, 'invoice-maker'));
const src = files.map(f => fs.readFileSync(f, 'utf8')).join('\n');
const re = /(?<![\w-])((?:hover:|focus:)?)(bg|text|border|ring|divide)-(white|black|transparent|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3})(?:\/(\d{1,3}))?(?![\w-])/g;
const found = new Map();
let m; while ((m = re.exec(src))) found.set(m[0], m);
const hex2rgb = h => { h = h.replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join(''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); };
const value = (name, alpha) => {
  let hex = name === 'white' ? '#ffffff' : name === 'black' ? '#000000' : name === 'transparent' ? null : colors[name.split('-')[0]][name.split('-')[1]];
  if (hex === null) return 'transparent';
  if (!hex) return null;
  if (alpha == null) return hex;
  const [r, g, b] = hex2rgb(hex); return `rgb(${r} ${g} ${b} / ${Number(alpha) / 100})`;
};
const esc = s => s.replace(/([:\/])/g, '\\$1');
const S = '.nfi-app:not(#nfi-reset)';
const out = [];
const order = ['', 'focus:', 'hover:'];
const entries = [...found.values()].sort((a, b) => order.indexOf(a[1]) - order.indexOf(b[1]) || a[0].localeCompare(b[0]));
for (const [cls, variant, kind, name, alpha] of entries) {
  const v = value(name, alpha); if (!v) continue;
  const pseudo = variant === 'hover:' ? ':hover' : variant === 'focus:' ? ':focus' : '';
  const sel = `.${esc(cls)}${pseudo}`;
  const themed = /^(white|slate-(50|100|800|900)|gray-(50|100)|neutral-(50|100))$/.test(name) && !variant && alpha == null;
  const decl = kind === 'bg' ? (themed ? `background-color: ${v} !important; color: inherit` : `background-color: ${v}`) : kind === 'text' ? `color: ${v}` : kind === 'border' ? `border-color: ${v}` : kind === 'ring' ? `--tw-ring-color: ${v}` : null;
  if (kind === 'divide') { out.push(`${S} ${sel} > :not([hidden]) ~ :not([hidden]) { border-color: ${v} !important; }`); continue; }
  out.push(`${S} ${sel}, ${S}${sel} { ${decl} !important; }`);
}
const header = `/* GENERATED by scripts/gen-invoice-theme-reset.cjs (run: node scripts/gen-invoice-theme-reset.cjs). Pins the Tailwind colors used in invoice-maker/.
   The app's Day/Night theme (index.html) repaints utilities like .bg-white and
   .text-slate-900 with !important; inside .nfi-app these rules win (id specificity),
   so the Invoice Maker and its invoices look the same in every theme.
   After adding a new color class in invoice-maker/, run the script again. */

/* Elements the theme styles directly */
${S} table tbody tr td { background-color: transparent !important; color: inherit !important; border-bottom-color: #e5e7eb !important; filter: none !important; }
${S} thead th { background-color: transparent !important; color: inherit !important; border-color: inherit !important; }
${S} :is(input, select, textarea) { color: #0f172a !important; background-color: #ffffff !important; border-color: #e2e8f0 !important; }
${S} :is(input, textarea)::placeholder { color: #94a3b8 !important; }
${S} :is(.border, .border-2, .border-b, .border-t) { border-color: #e2e8f0 !important; }
${S} :is(header, nav) { border-color: inherit !important; }
${S} label { color: inherit !important; }

/* Utilities */
`;
fs.writeFileSync(path.join(root, 'invoice-maker/theme-reset.css'), header + out.join('\n') + '\n');
console.log(out.length, 'rules');
